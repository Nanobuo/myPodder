export type StringKey = Key;

export const locale: string = typeof navigator !== "undefined" ? navigator.language : "it";
const isItalian = locale.toLowerCase().startsWith("it");
const table: Record<Key, Entry> = isItalian ? it : en;

function fill(text: string, args: (string | number)[]): string {
  return text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ""));
}

/** Testo tradotto; per i plurali il primo argomento è la quantità. */
export function t(key: Key, ...args: (string | number)[]): string {
  const entry = table[key] ?? it[key];
  if (typeof entry === "string") return fill(entry, args);
  const n = Number(args[0] ?? 0);
  return fill(n === 1 ? entry.one : entry.other, args);
}
